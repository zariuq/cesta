def nodes(value, label=None):
    if isinstance(value, list):
        matching = bool(value) and isinstance(value[0], Sym) and (
            value[0] == Sym("c:"+label) if label else value[0].startswith("c:"))
        if matching:
            yield value
        for child in value:
            yield from nodes(child, label)


def function(tree, name):
    matches = []
    for node in nodes(tree, "FunctionDefinition"):
        declarator_names = list(nodes(node[2], "NameDeclarator"))
        if declarator_names and declarator_names[0][1] == Sym(name):
            matches.append(node)
    assert len(matches) == 1, f"expected one definition of {name}"
    return matches[0]


def verify(filename, encoded):
    tree = parse(encoded)[0]
    name, constructors, variables = READINGS[filename]
    selected = function(tree, name) if name else tree
    checks = []
    for label, expected in constructors.items():
        actual = len(list(nodes(selected, label)))
        checks.append({"function": name, "constructor": label, "expected": expected, "actual": actual})
    for name, expected in variables.items():
        actual = sum(node[1] == Sym(name) for node in nodes(selected, "Var"))
        checks.append({"variable": name, "expected": expected, "actual": actual})
    if filename == "dangling_else.c":
        outer = list(nodes(selected, "If"))[0]
        checks.append({"nesting": "else belongs to inner if", "expected": 1, "actual": len(list(nodes(outer[2], "IfElse")))})
    if filename == "expressions.c":
        assignments = list(nodes(function(tree, "test3"), "Assign"))
        checks.append({"nesting": "assignment associates to right", "expected": 1,
                       "actual": sum(isinstance(node[2], list) and node[2][0] == Sym("c:Assign") for node in assignments)})
        sizes = list(nodes(function(tree, "test_sizeof"), "SizeofExpression"))
        checks.append({"nesting": "all three sizeof spellings apply to arr[0]", "expected": 3,
                       "actual": sum(isinstance(node[1], list) and node[1][0] == Sym("c:Subscript") for node in sizes)})
        subscript = list(nodes(function(tree, "test_sizeof"), "Subscript"))
        checks.append({"nesting": "no subscript applies to a sizeof result", "expected": 0,
                       "actual": sum(isinstance(node[1], list) and node[1][0] == Sym("c:SizeofExpression") for node in subscript)})
    failures = [check for check in checks if check["actual"] != check["expected"]]
    if failures:
        raise ValueError(f"{filename}: intended reading differs: {failures}")
    return checks
