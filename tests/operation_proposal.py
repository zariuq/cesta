"""Prime's operation table as one declaration, and a proposal over it.

The import declares every operation that one of Prime's capability lists or query rows names, with the
facts those places state; every other fact is "unknown". From the import Cesta derives the static, pure,
type-level and speculative lists and the query rows, and they equal Prime's own at the pinned revision.
They are compared as sets: the runtime turns the lists into per-symbol flags and the rows into an
if-chain, where order is not observed.

The proposal adds footprints for operations whose effects the pinned source settles, each with its
evidence. Its derived rows differ from Prime's exactly by the rows it adds, which are written out as a
MeTTa fragment for Prime's own generator (scripts/gen_execution_contracts.py checks every head against
symbol.h). Nothing is written to Prime's tree."""

