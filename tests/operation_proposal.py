BINARY = ROOT / "build/cesta"
WORK = ROOT / "build/operation-proposal"

# Resources: what Prime's query analysis observes is a store; work state is scratch to it.
RESOURCES = [("store", "store"), ("world", "store"), ("space", "store"), ("work", "scratch")]

# Footprints the pinned source settles, with the evidence (CeTTa paths at the pinned revision).
PROPOSED = {
    "space-push": ((), ("space",), "src/eval.c:71091: appends to an ordered space through the write resolver"),
    "space-pop": ((), ("space",), "src/eval.c:71165: space_pop on an ordered space"),
    "space-truncate": ((), ("space",), "src/eval.c:71204: truncate resolves its space for writing"),
    "space-get": (("space",), (), "src/eval.c:71204: get resolves its space for reading"),
    "space-len": (("space",), (), "src/eval.c:70976: petta_space_length_observe"),
    "space-peek": (("space",), (), "src/eval.c:71126: prime_native_observe_space_read, then space_peek"),
    "size": (("space",), (), "src/grounded.h:107: size reads live mutable space state"),
    "count-atoms": (("space",), (), "src/eval.c:71500: counts the atoms of a registry space"),
    "work-new": ((), ("work",), "src/eval_work.inc:1033: registers a new work state"),
    "work-budget": ((), ("work",), "src/eval_work.inc:1303: sets work->budget"),
    "work-cancel": ((), ("work",), "src/eval_work.inc:1306: closes the work handle"),
    "work-route": ((), ("work",), "src/eval_work.inc:1151: transfers or refuses the work"),
    "work-record": (("work",), (), "src/eval_work.inc:982: reads a const EvalWork"),
}
# Settled as not statically knowable from the head: they run the work's stored program.
DYNAMIC = {
    "work-take": "src/eval_work.inc:759: advances the stored program and mutates work state",
    "work-count": "src/eval_work.inc:865: advances the stored program and mutates work counters",
    "work-exists": "src/eval_work.inc:893: advances the stored program and retains the next answer",
}


def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def declaration(operations, footprints):
    lines = ["-- Prime's operation facts at the pinned revision, as one declaration. Generated by",
             "-- tests/operation_proposal.py; facts no source states are unknown.",
             "Module PrimeOperations {", "  Theory Operations() {", "    Empty Equations {",
             '      (Vocabulary) == (Vocabulary "cesta-operation/1"',
             "        (Resources " + " ".join(f'(Resource {r} "{k}")' for r, k in RESOURCES) + ")",
             "        (Charges) (Profiles));"]
    for spelling, o in operations:
        arities = sorted(set(o["type_arities"]) | set(o["registry_arities"]) | set(o.get("prime_arities", []))
                         | set(o["replay_forms"]))
        forms = " ".join("(Form" + "".join(' (Arg "unknown" "unknown" "unknown")' for _ in range(n)) + ")"
                         for n in arities)
        reads, writes = footprints[spelling] if footprints[spelling] is not None else (None, None)
        footprint = ('(Footprint "unknown")' if reads is None else
                     f"(Footprint (Reads {' '.join(reads)}) (Writes {' '.join(writes)}))".replace(" )", ")"))
        dispatch = "grounded" if o["pure"] or o["static"] else "unknown"
        through = f" (Through {' '.join(map(str, o['replay_forms']))})" if o["replay_forms"] else ""
        yes = lambda b: '"yes"' if b else '"no"'  # noqa: E731
        lines += [f'      (op_{o["symbol"]}) == (Operation "cesta-operation/1"',
                  f'        (Spelling {quote(spelling)}) (Symbol "{o["field"]}") (Dispatch "{dispatch}")',
                  f"        (Forms {forms}) {footprint}".replace("(Forms )", "(Forms)"),
                  '        (Context (Blocks "unknown") (Branches "unknown") (Progress "unknown") (Charges))',
                  '        (Result "unknown")',
                  f'        (Declared (Static {yes(o["static"])}) (TypePure {yes(o["type_pure"])}) '
                  f'(Speculative {yes(o["speculative_listed"])}) (Replay "refused"{through}))',
                  "        (Profiles));"]
    lines += ["    }", "  }", "}"]
    return "\n".join(lines) + "\n"


def run(*args):
    return subprocess.run([str(BINARY), "operations", *args], capture_output=True, text=True, check=True).stdout


def derived(module):
    rows, = parse(run("rows", str(module), "Operations").encode())
    out = {}
    for part in rows[1:]:
        head = str(part[0])
        out[head] = ({(str(q[0]), int(str(q[1]))) for q in part[1:]} if head == "Query"
                     else {str(x) for x in part[1:]})
    return out


BASE = 2 ** 32 + 1
CHUNK = 25
LAWS = ["Mettapedia.GSLT.LanguageDef.OperationContracts.tableAdmitted_of_codes",
        "Mettapedia.GSLT.LanguageDef.OperationContracts.rowsAdmitted_of_codes",
        "Mettapedia.GSLT.LanguageDef.OperationContracts.chunkCodes_append",
        "Mettapedia.GSLT.LanguageDef.OperationContracts.chunkRowCodes_append",
        "Mettapedia.GSLT.LanguageDef.OperationContracts.strCode_injective"]


def code(text):
    """OperationContracts.strCode: the characters as digits code + 1 in BASE, least significant first."""
    value = 0
    for c in reversed(text):
        value = value * BASE + ord(c) + 1
    return value


def nest(op, parts):
    """Right-nested application of a binary combinator: op p0 (op p1 (… pn))."""
    term = parts[-1]
    for p in reversed(parts[:-1]):
        term = f"{op} ({p}) ({term})"
    return term


def kernel_admission(module, label, memory_mb):
    """The Lean kernel admits the table and its derived rows, a chunk of operations per decision."""
    records = parse(run("check", str(module), "Operations").encode())
    rows, = parse(run("rows", str(module), "Operations").encode())
    ops = records[1:]
    lists = {str(part[0]): part[1:] for part in rows[1:]}
    lines = ["import Mettapedia.GSLT.LanguageDef.OperationContracts",
             "open Mettapedia.GSLT.LanguageDef.MacroExportPlan Mettapedia.GSLT.LanguageDef.OperationContracts",
             "open Mettapedia.GSLT.LanguageDef.ExportCounterTables",
             "set_option Elab.async false", "set_option maxRecDepth 100000",
             "set_option synthInstance.maxSize 1024", f"namespace {label}",
             f"def vocabulary : Atom := {atom(records[0])}",
             'def v : Vocabulary := (decodeVocabulary vocabulary).getD ⟨"", [], [], []⟩',
             "theorem vocabularyDecoded : decodeVocabulary vocabulary = some v := by decide +kernel",
             "theorem vocabularyLawful : vocabularyOk v = true := by decide +kernel",
             "abbrev RowCodes := List Nat × List Nat × List Nat × List Nat × List (Nat × Nat) × List Nat"]
    chunks = [ops[i:i + CHUNK] for i in range(0, len(ops), CHUNK)]
    codes, row_codes = [], []
    for j, chunk in enumerate(chunks):
        names = [f"op{j}_{k}" for k in range(len(chunk))]
        for n, r in zip(names, chunk):
            lines.append(f"def {n} : Atom := {atom(r)}")
        lines.append(f"def c{j} : List Atom := [{', '.join(names)}]")
        triples = [(code(str(r[1])), code(r[2].data.decode()), code(str(r[3]))) for r in chunk]
        lines.append(f"def t{j} : List (Nat × Nat × Nat) := [{', '.join(f'({a}, {b}, {c})' for a, b, c in triples)}]")
        lines.append(f"theorem codes{j} : chunkCodes v c{j} = some t{j} := by decide +kernel")
        symbols = {str(r[3]) for r in chunk}

        def part(head):
            return [x for x in lists[head] if (str(x[0]) if head == "Query" else str(x)) in symbols]
        lists_text = ", ".join(f"[{', '.join(str(code(str(x))) for x in part(h))}]"
                               for h in ("Static", "Pure", "TypePure", "Speculative"))
        query = ", ".join(f"({code(str(q[0]))}, {q[1]})" for q in part("Query"))
        unknown = ", ".join(str(code(str(x))) for x in part("Unknown"))
        lines.append(f"def r{j} : RowCodes := ({lists_text}, [{query}], [{unknown}])")
        lines.append(f"theorem rows{j} : chunkRowCodes v c{j} = some r{j} := by decide +kernel")
        codes.append(f"codes{j}")
        row_codes.append(f"rows{j}")

    def right(op, parts):
        term = parts[-1]
        for p in reversed(parts[:-1]):
            term = f"{op} {p} ({term})" if op else f"{p} ++ ({term})"
        return term
    n = len(chunks)
    lines.append(f"def table : List Atom := {right('', [f'c{j}' for j in range(n)])}")
    lines.append(f"def triples : List (Nat × Nat × Nat) := {right('', [f't{j}' for j in range(n)])}")
    lines.append(f"def rowCodes : RowCodes := {right('appendCodes', [f'r{j}' for j in range(n)])}")
    lines.append(f"def rows : Atom := {atom(rows)}")
    lines.append(f"theorem allCodes : chunkCodes v table = some triples := {right('chunkCodes_append', codes)}")
    for name, proj in (("Names", "(·.1)"), ("Spellings", "(·.2.1)"), ("Symbols", "(·.2.2)")):
        lines.append(f"theorem distinct{name} : allDistinct (triples.map {proj}) .leaf = true := by decide +kernel")
    lines.append("theorem admitted : tableAdmitted vocabulary table = true :=\n"
                 "  tableAdmitted_of_codes vocabularyDecoded vocabularyLawful allCodes distinctNames distinctSpellings "
                 "distinctSymbols")
    lines.append(f"theorem allRows : chunkRowCodes v table = some rowCodes := {right('chunkRowCodes_append', row_codes)}")
    lines.append("theorem recordedRows : (decodeRows rows).map rowsCodes = some rowCodes := by decide +kernel")
    lines.append("theorem rowsRecorded : rowsAdmitted vocabulary table rows = true :=\n"
                 "  rowsAdmitted_of_codes vocabularyDecoded admitted allRows recordedRows")
    lines.append(f"end {label}")
    lines += [f"#print axioms {law}" for law in LAWS]
    lines += [f"#print axioms {label}.admitted", f"#print axioms {label}.rowsRecorded"]
    started = time.monotonic()
    output = kernel(WORK.resolve() / f"{label}.lean", lines, memory_mb)
    for match in re.finditer(r"'([^']+)' depends on axioms:\s*\[(.*?)\]", output, re.DOTALL):
        found = {x.strip() for x in match[2].split(",") if x.strip()}
        if not found <= {"propext", "Classical.choice", "Quot.sound"}:
            raise RuntimeError("unexpected axioms: " + str(found))
    return {"operations": len(ops), "chunks": len(chunks), "seconds": round(time.monotonic() - started, 1)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--lean-memory-mb", type=int, default=12288)
    args = parser.parse_args()
    models = model_snapshot()
    shutil.rmtree(WORK, ignore_errors=True)
    WORK.mkdir(parents=True)
    facts = operation_audit.gather(operation_audit.REVISION)
    operations, lists, query = facts["operations"], facts["lists"], facts["query"]
    assert set(query.values()) <= {1, 2}, "a query row with both bits"
    named = lists["static"] | lists["pure"] | lists["type-pure"] | lists["speculative"] | set(query)
    chosen = sorted((t, o) for t, o in operations.items()
                    if o["field"] in named or t in PROPOSED or t in DYNAMIC)
    for t, o in chosen:
        o["symbol"] = o["field"]
    footprints = {}
    for t, o in chosen:
        bits = query.get(o["field"], 0)
        footprints[t] = (((), ()) if o["pure"] else (("store",), ()) if bits == 1 else ((), ("world",)) if bits == 2
                         else None)
    imported = WORK / "PrimeOperations.module"
    imported.write_text(declaration(chosen, footprints))
    run("check", str(imported), "Operations")
    rows = derived(imported)
    prime = {"Static": lists["static"], "Pure": lists["pure"],
             "TypePure": lists["type-pure"] - lists["pure"], "Speculative": lists["speculative"] - lists["pure"],
             "Query": set(query.items())}
    lossless = {k: rows[k] == v for k, v in prime.items()}
    assert all(lossless.values()), {k: (sorted(rows[k] - v)[:5], sorted(v - rows[k])[:5])
                                    for k, v in prime.items() if rows[k] != v}

    # The proposal: footprints the source settles. A proposed space reader or writer replaces an
    # unknown footprint only; one that Prime already rows is kept as Prime rows it.
    proposed_footprints = dict(footprints)
    for t, (reads, writes, _) in PROPOSED.items():
        if footprints.get(t) is None:
            proposed_footprints[t] = (reads, writes)
    proposal = WORK / "PrimeOperationsProposed.module"
    proposal.write_text(declaration(chosen, proposed_footprints))
    run("check", str(proposal), "Operations")
    proposed_rows = derived(proposal)
    added = sorted(proposed_rows["Query"] - rows["Query"])
    removed = sorted(rows["Query"] - proposed_rows["Query"])
    assert not removed, removed
    for k in ("Static", "Pure", "TypePure", "Speculative"):
        assert proposed_rows[k] == rows[k], k
    known = sorted(set(rows["Unknown"]) - set(proposed_rows["Unknown"]))
    spellings = {o["field"]: t for t, o in chosen}
    fragment = [f"(query-head {spellings[f]} {'world-write' if e == 2 else 'relational-query'})" for f, e in added]
    (WORK / "proposed-query-heads.metta").write_text(
        ";; Proposed additions to lib/gslt_execution_contracts.metta, derived from\n"
        ";; PrimeOperationsProposed.module; each has its evidence in proposal.json.\n" + "\n".join(fragment) + "\n")
    subprocess.run([str(BINARY), "operations", "header", str(proposal), "Operations", "-o",
                    str(WORK / "prime_operations.generated.h")], check=True)
    kernel_import = kernel_admission(imported, "PrimeImport", args.lean_memory_mb)
    kernel_proposal = kernel_admission(proposal, "PrimeProposal", args.lean_memory_mb)
    if model_snapshot() != models:
        raise RuntimeError("the Lean operation model changed during admission")
    summary = {"revision": operation_audit.REVISION, "imported_operations": len(chosen),
               "kernel": {"import": kernel_import, "proposal": kernel_proposal},
               "lossless": lossless, "proposed_footprints": {t: {"reads": list(r), "writes": list(w),
                                                                  "evidence": e} for t, (r, w, e) in PROPOSED.items()},
               "dynamic": DYNAMIC, "added_query_rows": [[spellings[f], e] for f, e in added],
               "newly_known_footprints": [spellings[f] for f in known],
               "still_unknown": len(proposed_rows["Unknown"])}
    (WORK / "proposal.json").write_text(json.dumps(summary, indent=1) + "\n")
    print(f"operation proposal: {len(chosen)} Prime operations declared at {operation_audit.REVISION}; the derived "
          "static, pure, type-level and speculative lists and the query rows equal Prime's; the proposal settles "
          f"{len(known)} more footprints from the source and adds {len(added)} query rows "
          f"({', '.join(spellings[f] for f, _ in added)}); {len(proposed_rows['Unknown'])} footprints remain unknown; "
          f"the kernel admits both tables and their rows in {kernel_import['chunks']} chunks each "
          f"({kernel_import['seconds']} s, {kernel_proposal['seconds']} s)")


if __name__ == "__main__":
    main()
